'use strict';

/**
 * Свежая база на каждый прогон тестов.
 *
 * Подключать первой строкой в каждом самотесте — до всего, что тянет db.js.
 *
 * Зачем. Без TRAPEZA_DB база берётся по умолчанию: `<папка проекта>/data/
 * trapeza.db`. Отсюда две беды.
 *
 * Первая: прогоны перестают быть независимыми. Второй `npm test` подряд
 * падает — нумерация документов продолжается с прошлого раза, и проверка
 * «номер присвоен сам → 1» видит 15.
 *
 * Вторая тяжелее. На сервере приложение развёрнуто в /opt/trapeza, и боевая
 * база клиентов лежит ровно по этому пути. `npm test`, запущенный там, залил
 * бы в неё тестовых пользователей, организации и документы. README при этом
 * прямо советует `cd trapeza && npm test`.
 *
 * Поэтому: своя временная база, если путь не задан явно.
 *
 * ── А если задан ──
 *
 * Раньше здесь было написано «задан — уважаем, это осознанное решение
 * запускающего». Оказалось, что заданным он бывает и без всякого решения.
 *
 * На боевом сервере путь лежит в .env рядом с ключами. Достаточно один раз
 * выполнить `set -a && . ./.env` — например чтобы запустить команду с
 * настоящими настройками, — и TRAPEZA_DB останется в оболочке. Запущенное
 * следом обновление унаследует его вместе со всем остальным, и прогон,
 * который выписывает документы и заводит контрагентов, отработает по живой
 * базе клиентов. Никто ничего не решал: переменная приехала сама.
 *
 * Поэтому путь мы принимаем, но только если база по нему пустая. Есть в ней
 * люди — останавливаемся и говорим почему. Прогон всё равно начинает с
 * чистого листа: продолжать чужую нумерацию он не умеет, и упал бы следом,
 * но уже после того, как записал бы своё.
 */

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

/*
 * Журнал вебхуков оплаты — тоже во временную папку. lava-webhook.js пишет
 * его рядом с кодом, в data/, и прогоны, которые его подключают, дописывали
 * тестовые платежи в боевой журнал: на сервере это тот самый файл, по
 * которому разбирают спорные оплаты.
 */
process.env.LAVA_LOG = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'trapeza-lava-')), 'lava-webhook.log');

if (!process.env.TRAPEZA_DB) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'trapeza-selftest-'));
  process.env.TRAPEZA_DB = path.join(dir, 'test.db');
} else {
  const target = process.env.TRAPEZA_DB;
  /*
   * Пустая — значит без единой записи в ЛЮБОЙ таблице.
   *
   * Раньше считались только люди бота (bot_users). Но db.js общий с сервером
   * смет, и его боевая база — заказы, меню, сверки — пользователей бота не
   * содержит вовсе: заслонка признавала её пустой, и прогон писал в неё свои
   * документы. А базу, которая не открылась, пропускали дальше — хотя
   * доказать, что она пустая, тогда нечем.
   */
  let rows = 0;
  let unreadable = '';
  if (fs.existsSync(target) && fs.statSync(target).size > 0) {
    try {
      const { DatabaseSync } = require('node:sqlite');
      const db = new DatabaseSync(target, { readOnly: true });
      const tables = db.prepare(
        "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'",
      ).all();
      for (const t of tables) {
        rows += Number(db.prepare(`SELECT COUNT(*) AS n FROM "${t.name.replace(/"/g, '""')}"`).get().n) || 0;
      }
      db.close();
    } catch (e) {
      unreadable = e.message;
    }
  }
  if (rows > 0 || unreadable) {
    console.error(
      (unreadable
        ? `\n⛔ Прогон остановлен: базу не удалось открыть и убедиться, что она пустая.\n`
          + `   TRAPEZA_DB=${target}\n   ${unreadable}\n\n`
        : '\n⛔ Прогон остановлен: база не пустая.\n'
          + `   TRAPEZA_DB=${target}\n`
          + `   записей в ней: ${rows}\n\n`)
      + '   Самотесты выписывают документы и заводят контрагентов. Начинать\n'
      + '   они должны с пустой базы — иначе чужие записи смешаются с их\n'
      + '   собственными, а на боевом сервере это записи клиентов.\n\n'
      + '   Чаще всего причина такая: в оболочку загружен боевой .env\n'
      + '   (`set -a && . ./.env`), и TRAPEZA_DB приехал оттуда сам.\n'
      + '   Тогда достаточно запустить обновление в чистой оболочке.\n\n'
      + '   Нужен свой путь — берите новый файл:\n'
      + '     TRAPEZA_DB=/tmp/trapeza-$(date +%s).db npm test\n',
    );
    process.exit(1);
  }
}

module.exports = process.env.TRAPEZA_DB;
