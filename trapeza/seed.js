function seedCounterparty(cp) {
  const exists = db.prepare('SELECT id FROM counterparties WHERE name = ?').get(cp.name);
  if (exists) return exists.id;
  const info = db.prepare(`
    INSERT INTO counterparties(name, full_name, inn, kpp, extra, kind, contract,
                               opening_balance, opening_date, period_end, signer)
    VALUES(?,?,?,?,?,?,?,?,?,?,?)`).run(
    cp.name, cp.full_name, cp.inn, cp.kpp || '', cp.extra || '', cp.kind, cp.contract,
    cp.opening_balance, cp.opening_date, cp.period_end, cp.signer || '');
  const id = Number(info.lastInsertRowid);
  const ins = db.prepare(`INSERT INTO operations(cp_id, date, kind, doc, debit, credit, sort)
                          VALUES(?,?,?,?,?,?,?)`);
  cp.ops.forEach((o, i) => ins.run(id, o[0], o[1], o[2], o[3], o[4], i));
  return id;
}

function run() {
  for (const [k, v] of Object.entries(SETTINGS)) {
    if (getSetting(k) === null) setSetting(k, v);
  }

  // Меню перезаливаем при смене версии набора (заказы и сверки не трогаем).
  if (getSetting('menu_version') !== MENU_VERSION) {
    db.exec('DELETE FROM menu_items');
    const ins = db.prepare(`INSERT INTO menu_items(name, description, unit, price, category, menu_type,
                                                   photo, price_tbd, sort)
                            VALUES(?,?,?,?,?,?,?,?,?)`);
    let i = 0;
    for (const [type, list] of [['furshet', MENU], ['banket', MENU_BANKET]]) {
      list.forEach((m) => ins.run(m[0], m[1] || '', m[2], m[3], m[4], type, m[6] || '', m[5] || 0, i++));
    }
    setSetting('menu_version', MENU_VERSION);
    console.log(`  меню: загружено ${MENU.length} фуршет + ${MENU_BANKET.length} банкет `
      + `= ${MENU.length + MENU_BANKET.length} позиций (версия ${MENU_VERSION})`);
  }
  if (getSetting('slogan') === 'Кейтеринг · банкеты · кофе-брейки') {
    setSetting('slogan', SETTINGS.slogan);
  }

  seedCounterparty(SARYCHEV);
  seedCounterparty(FABRIKA);

  const cps = db.prepare('SELECT COUNT(*) AS n FROM counterparties').get().n;
  const ops = db.prepare('SELECT COUNT(*) AS n FROM operations').get().n;
  console.log(`  контрагентов: ${cps}, операций: ${ops}`);
}

if (require.main === module) {
  console.log('Наполнение базы «Трапеза»…');
  run();
  console.log('Готово.');
}

