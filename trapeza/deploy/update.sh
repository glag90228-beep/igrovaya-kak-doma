#!/usr/bin/env bash
#
# Обновление боевого сервера.
#
#   bash /opt/trapeza/deploy/update.sh
#
# Забирает свежий код из ветки, прогоняет проверки в отдельной папке и —
# только если они прошли — раскладывает в /opt/trapeza и перезапускает службы.
#
# Порядок именно такой: проверки ДО раскладки. Раньше код копировался в
# /opt/trapeza первым, а проверки шли следом, с расчётом, что запущенные
# процессы держат старый код в памяти. Не держат: бот подгружает часть
# модулей по ходу работы, упавшая служба сама перезапускается через пять
# секунд, таймер копий запускает backup.js с диска. Упавший прогон оставлял
# непроверенный код там, откуда его возьмёт первый же такой запуск.

set -euo pipefail

# Всё тело — внутри функции, и вызывается она последней строкой файла.
#
# Не украшение, а необходимость: скрипт перезаписывает сам себя. Раскладывая
# свежий код в /opt/trapeza, он кладёт новый update.sh поверх того, который
# bash в эту секунду читает, — а тот продолжает читать с прежнего места в
# БАЙТАХ. Стоит новому файлу отличаться длиной, и чтение попадает в середину
# строки: обновление обрывалось на «еудаче: command not found» — обрывке слова
# из комментария ниже.
#
# Разбор функции bash делает целиком, до первой её команды. Значит к моменту,
# когда мы что-то копируем, файл уже прочитан весь, и подменять его безопасно.
main() {

BRANCH="${BRANCH:-claude/estimates-reconciliation-agent-1oisy7}"
REPO="${REPO:-https://github.com/glag90228-beep/igrovaya-kak-doma.git}"
SRC="${SRC:-/root/trapeza-src}"
APP="${APP:-/opt/trapeza}"
OWNER="${OWNER:-trapeza}"
SERVICES="${SERVICES:-trapeza-bot trapeza-miniapp trapeza-lava}"

echo "Ветка:  $BRANCH"
echo "Сервер: $APP"
echo

# Раскладке нужен rsync. install.sh его ставит, но проверяем здесь, в самом
# начале: узнать о его отсутствии после двухминутного прогона обидно.
command -v rsync >/dev/null 2>&1 || apt-get install -y rsync

# ---------- 1. Свежий код ----------
#
# Клон живёт отдельно от рабочей папки: в /opt/trapeza лежат .env, база и
# node_modules, которых в репозитории нет и быть не должно.

# Логин git не спрашивает никогда.
#
# Репозиторий публичный, вход ему не нужен. Но при испорченном ответе git
# решает, что дело в правах, и просит логин — а скрипт в этот момент встаёт
# намертво и ждёт ввода. Вслепую это выглядит как «обновление зависло», и
# всё, что человек напечатает дальше, уходит не в оболочку, а в приглашение.
export GIT_TERMINAL_PROMPT=0

# Обмен: сначала как обычно, при неудаче — первой версией протокола.
#
# На боевом сервере ответ по второй версии приходит испорченным: git не
# разбирает его («expected flush after ref listing») и просит логин, хотя
# curl забирает тот же адрес с кодом 200. Первая версия проходит.
#
# Держим обе попытки, а не одну первую: причина снаружи, она может исчезнуть,
# и незачем навсегда оставаться на старом протоколе.
git_try() {
  git -C "$SRC" "$@" 2>/dev/null && return 0
  echo "Обычный обмен не прошёл — пробую первой версией протокола."
  git -C "$SRC" -c protocol.version=1 "$@"
}

if ! git -C "$SRC" remote -v 2>/dev/null | grep -q igrovaya-kak-doma; then
  echo "Клона нет или он от другого репозитория — забираю заново."
  rm -rf "$SRC"
  git clone --quiet "$REPO" "$SRC" 2>/dev/null \
    || git -c protocol.version=1 clone --quiet "$REPO" "$SRC"
fi
git_try fetch --quiet origin "$BRANCH"
git -C "$SRC" reset --quiet --hard "origin/$BRANCH"
echo "Забрал: $(git -C "$SRC" log --oneline -1)"

# ---------- 2. Черновая папка ----------
#
# Проверяем код там, куда службы не смотрят. Зависимости берём боевые, если
# их список не менялся, иначе ставим в черновую отдельно — боевые остаются
# нетронутыми до успешного прогона.

STAGE="${STAGE:-$APP.next}"
rm -rf "$STAGE"
mkdir -p "$STAGE"
cp -r "$SRC/trapeza/." "$STAGE/"
DEPS_CHANGED=0
if ! cmp -s "$SRC/trapeza/package-lock.json" "$APP/.package-lock.deployed" 2>/dev/null; then
  DEPS_CHANGED=1
  echo "Список зависимостей изменился — ставлю в черновую папку."
  (cd "$STAGE" && npm install --omit=dev --no-audit --no-fund >/dev/null)
elif [ -d "$APP/node_modules" ]; then
  ln -s "$APP/node_modules" "$STAGE/node_modules"
fi

# ---------- 3. Проверки ----------

echo
echo "Прогоняю проверки — это около двух минут."

# Проверки идут в СВОЁМ окружении, а не в том, что досталось от оболочки.
#
# Настройки боевого сервера меняют поведение продукта: FREE_DOCS=5 включает
# настоящий платный предел, а TRAPEZA_DB указывает на базу клиентов. Стоит
# один раз выполнить `set -a && . ./.env` — скажем, чтобы запустить команду
# с настоящими ключами, — и всё это остаётся в оболочке. Запущенное следом
# обновление наследует их молча: прогон упирался в платный предел на шестом
# документе и падал так, будто сломан код, а до того успевал выписать
# документы и завести контрагентов в живой базе.
#
# Поэтому TRAPEZA_DB именно УБИРАЕМ, а не задаём своим путём. Прогонов
# девять, идут они одним npm test, и общая база им не годится: первый
# заводит людей, а второй на них и споткнётся — заслонка в selftest-db.js
# как раз это и ловит. Без переменной каждый прогон делает себе временную
# базу сам, как и задумано.
#
# Пределы задаём явно: их ждут сами проверки. Вычищать окружение целиком
# нельзя — PATH, HOME и NODE_PATH прогону нужны.
if ! (cd "$STAGE" && env -u TRAPEZA_DB FREE_DOCS=1000 ENFORCE_LIMIT=1 npm test); then
  echo
  echo "⚠️  ПРОВЕРКИ НЕ ПРОШЛИ. Код в $APP не тронут, службы не перезапущены —"
  echo "    работает прежняя версия. Пришлите вывод выше — разберёмся."
  exit 1
fi

# ---------- 4. Раскладка ----------
#
# Папка на сервере приводится в точное соответствие с репозиторием: файл,
# которого в git больше нет, удаляется. Раньше здесь был `cp -r` поверх, и
# удалённый из репозитория модуль продолжал лежать в /opt/trapeza — по папке
# уже нельзя было сказать, какой код на самом деле работает.
#
# Защищено от удаления то, чего в git нет и быть не должно:
#   data/                 — база клиентов, журналы вебхуков, замки;
#   node_modules/         — зависимости, ставятся отдельно;
#   .env и .env.bak.*     — ключи; копии делает nginx-merge.sh перед правкой;
#   .package-lock.deployed — по нему шаг 2 решает, ставить ли зависимости:
#                            сотри его, и каждое обновление ставило бы их заново.
# protect не даёт удалить, exclude — перезаписать. data и .env защищены
# обоими способами, как в install.sh: ошибка здесь стоит боевой базы.
rsync -a --delete \
  --filter='protect /data' --filter='protect node_modules' \
  --filter='protect /.env*' --filter='protect /.package-lock.deployed' \
  --exclude /data --exclude node_modules --exclude /.env \
  "$SRC/trapeza/" "$APP/"
if [ "$DEPS_CHANGED" = 1 ]; then
  (cd "$APP" && npm install --omit=dev --no-audit --no-fund >/dev/null)
  cp "$SRC/trapeza/package-lock.json" "$APP/.package-lock.deployed"
fi
chown -R "$OWNER:$OWNER" "$APP" 2>/dev/null || true
rm -rf "$STAGE"
echo "Проверки прошли — разложил в $APP"

# ---------- 5. Перезапуск ----------

# shellcheck disable=SC2086
systemctl restart $SERVICES

# Ждём, пока службы поднимутся, а не смотрим снимок через две секунды.
#
# Раньше здесь было `sleep 2` и показ состояния. Служба, упавшая на старте,
# перезапускается через пять секунд (RestartSec=5) и обычно поднимается со
# второго раза — порт не сразу отпускается прежним процессом. Снимок на
# второй секунде попадал ровно в эту яму и показывал «activating
# (auto-restart), Result: exit-code». Выглядит как авария, хотя через
# несколько секунд всё работает; а настоящую аварию от этого не отличить.
#
# Теперь ждём до двадцати секунд и говорим о том, чем дело кончилось.
echo
for _ in $(seq 1 20); do
  ALL_UP=1
  for s in $SERVICES; do
    systemctl is-active --quiet "$s" || ALL_UP=0
  done
  [ "$ALL_UP" = 1 ] && break
  sleep 1
done

FAILED=""
for s in $SERVICES; do
  if systemctl is-active --quiet "$s"; then
    echo "  ✅ $s — работает"
  else
    echo "  ❌ $s — НЕ поднялась"
    FAILED="$FAILED $s"
  fi
done

# Вывод служб уходит в файл, а не в journalctl (StandardOutput=append:…),
# поэтому `journalctl -u` показывает только строки systemd, без причины.
# Раз служба не встала — сразу показываем то место, где причина есть.
if [ -n "$FAILED" ]; then
  for s in $FAILED; do
    LOG="/var/log/trapeza/${s#trapeza-}.log"
    echo
    echo "── последнее из $LOG ──"
    [ -f "$LOG" ] && tail -20 "$LOG" || echo "   файла нет"
  done
  echo
  echo "⚠️  Код разложен и проверки прошли, но службы не поднялись."
  exit 1
fi

echo
echo "Готово. Что стоит посмотреть глазами:"
echo "  • откройте приложение — заставка, потом главный экран;"
echo "  • «Ждут оплаты» — сумма вверху должна сходиться со списком;"
echo "  • карточку клиента — там повторяющаяся операция и акт сверки."
echo
echo "Сайт обновляется отдельно:  bash $APP/deploy/site.sh"

}

# Вызов последней строкой — к этому месту файл прочитан целиком, и дальнейшая
# подмена его на диске выполнению уже не мешает.
#
# exit здесь обязателен, и одной обёртки без него мало. Отработав main, bash
# идёт за следующей командой ПО ПРЕЖНЕМУ СМЕЩЕНИЮ В БАЙТАХ — и, если приехавший
# файл длиннее прежнего, дочитывает его хвост. На настоящем update.sh это
# воспроизводится: 6941 байт было, 7285 приехало, и после «Готово» вылезало
# «unexpected EOF while looking for matching "» с кодом 2. Выкладка при этом
# прошла целиком, а человек видел ошибку и был обязан решить, что всё упало.
#
# Хуже другой случай: если новый файл длиннее ровно на длину этой строки,
# хвостом окажется целое «main "$@"» — и обновление молча выполнится дважды,
# со вторым npm test и вторым перезапуском служб.
#
# exit и main разбираются вместе, до запуска первой из них, поэтому дочитывать
# после выхода уже нечего.
main "$@"; exit $?
