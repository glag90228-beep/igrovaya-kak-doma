console.log('\n=== Сторно ===');
{
  /*
   * В выделенной колонке направление задаёт сама колонка, поэтому минус в
   * ней может означать только отмену: сторно ошибочного зачисления или
   * возврат. Раньше `if (income)` считало истинным любое ненулевое число,
   * такая строка проходила приходом, а Math.abs стирал знак. В приложении
   * она вставала рядом с настоящей оплатой, обе привязывались к тому же
   * контрагенту по ИНН — и одно нажатие «Занести» закрывало долг дважды.
   */
  const csv = [
    'Дата,Контрагент,ИНН,Сумма по дебету,Сумма по кредиту,Назначение',
    '15.08.2026,ООО Заря,7701234567,,"50000,00",Оплата по счету 12',
    '16.08.2026,ООО Заря,7701234567,,"-50000,00",СТОРНО ошибочно зачисленной суммы',
  ].join('\n');
  const { rows } = bank.parseStatement(Buffer.from(csv, 'utf8'));
  ok(rows.length === 2, 'разобраны обе строки', rows.length);
  ok(rows[0] && rows[0].incoming === true, 'настоящая оплата — приход');
  ok(rows[1] && rows[1].incoming === false && rows[1].amount === 50000,
    'сторно в колонке прихода — расход, а не второе поступление',
    rows[1] && `${rows[1].amount} приход=${rows[1].incoming}`);

  // А в одной общей колонке минус значит другое: он просто обозначает
  // расход, и направление всё равно берётся из типа операции.
  const one = [
    'Дата операции,Тип операции,Контрагент,ИНН,Сумма операции,Назначение платежа',
    '11.08.2026,Расход,ООО Аренда,7809876543,"-12500,00",Аренда',
  ].join('\n');
  const r2 = bank.parseStatement(Buffer.from(one, 'utf8')).rows;
  ok(r2[0] && r2[0].incoming === false && r2[0].amount === 12500,
    'в общей колонке знак направление не переворачивает',
    r2[0] && `${r2[0].amount} приход=${r2[0].incoming}`);
}

