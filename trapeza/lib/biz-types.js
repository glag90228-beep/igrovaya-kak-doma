'use strict';

/**
 * Чем занимается бизнес — и что из этого следует.
 *
 * Зачем это нужно. Единственная настройка, в которой новичок гарантированно
 * теряется, — «откуда берётся долг»: по акту, по счёту или вручную. Вопрос
 * бухгалтерский, и человек, который открыл бота, чтобы выставить счёт, не
 * обязан на него отвечать. Зато на вопрос «чем вы занимаетесь» он отвечает
 * не задумываясь, а дальше правило выводится само.
 *
 * Почему выбор именно такой:
 *
 *   аренда      — акт по ГК РФ не обязателен и часто не составляется вовсе,
 *                 а счёт выставляется каждый месяц. Долг возникает по счёту.
 *   подряд      — деньги зарабатываются подписанным актом; счёт до работ —
 *                 только просьба заплатить. Долг возникает по акту.
 *   торговля    — обязательство появляется с отгрузкой: накладная или УПД.
 *   услуги      — то же, что подряд: акт закрывает работу.
 *   производство— отгрузка, как в торговле.
 *
 * Кроме основания долга у вида деятельности есть второе следствие: что в
 * этом деле повторяется каждый месяц. У аренды — счёт, у обслуживания —
 * акт. Из этого получается подсказка «настроить напоминание», и только
 * подсказка: правило само ничего не выписывает, в нужный день бот приходит
 * с предложением, а кнопку жмёт человек (lib/recurring.js).
 *
 * Так и было задумано с самого начала. На сервере лежал набор «шаблонов
 * рабочих процессов» с правилами вида «выписать документ такого-то числа»
 * и «отправить письмо должнику» — выписывать документы и писать чужим
 * клиентам за человека нельзя, поэтому от шаблонов осталось ровно то, что
 * можно предложить: основание долга и повод для напоминания.
 */

