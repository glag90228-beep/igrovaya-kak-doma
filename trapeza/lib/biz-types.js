const get = (key) => TYPES[key] || null;
const list = () => Object.entries(TYPES).map(([key, t]) => ({ key, ...t }));
const nameOf = (key) => (TYPES[key] ? TYPES[key].name : '');

/**
 * Что в этом деле повторяется каждый месяц — или null, если ничего.
 *
 * Раньше подряд, торговля и производство сюда не попадали: я рассуждал, что
 * объём там каждый раз разный и напоминание приведёт к лишнему документу.
 * Рассуждение было неверным — напоминание документа не выписывает. Правило
 * заводится пустым, без позиций и сумм, а кнопка в нужный день открывает
 * обычный мастер с уже выбранным клиентом. Забыть закрыть месяц можно в
 * любом деле, и подрядчику это стоит дороже прочих.
 *
 * Числа взяты по тому, когда в этих делах закрывают месяц:
 *   аренда         1-го   — счёт вперёд, за наступающий месяц;
 *   остальные      25-го  — время собрать закрывающий документ до конца
 *                           месяца и успеть подписать.
 *
 * «Другое» остаётся без напоминания: там и основание долга ручное, то есть
 * про это дело мы не знаем ничего и советовать нечего.
 */
const routineOf = (key) => (TYPES[key] && TYPES[key].routine) || null;

module.exports = { TYPES, get, list, nameOf, routineOf };
