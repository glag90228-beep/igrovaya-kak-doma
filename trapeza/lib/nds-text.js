'use strict';

/**
 * Сверка НДС, написанного словами, с НДС, который посчитан.
 *
 * Назначение платежа и текст письма человек пишет руками, и там регулярно
 * остаётся прошлогоднее «в том числе НДС 20%» — потому что назначение
 * копируют из предыдущей платёжки, а ставка с 2026 года другая. Банк такую
 * платёжку проведёт, а вот у получателя назначение разойдётся с суммой в
 * счёте, и разбираться придётся уже втроём с бухгалтерией.
 *
 * Мы не переписываем текст за человека: назначение платежа — его слова, и
 * молча менять их в платёжном документе нельзя. Мы только показываем
 * расхождение до того, как документ уйдёт.
 */

const { round2 } = require('./money');

/**
 * Ставка и сумма, названные в тексте.
 *
 * Ищем то, как это пишут живые люди: «НДС 22%», «в том числе НДС 20 %»,
 * «НДС 22% - 1830,00», «без НДС», «НДС не облагается». Регистр не важен,
 * а вот «\b» вокруг русских слов не работает вовсе — граница слова в JS
 * знает только латиницу, поэтому опираемся на пробелы и знаки.
 *
 * @returns {{rate:number|null, exempt:boolean, sum:number|null}|null}
 */
function vatInText(text) {
  const t = String(text || '');
  if (!t) return null;

  if (/(?:без\s*ндс|ндс\s*не\s*облага|не\s*облагается\s*ндс)/i.test(t)) {
    return { rate: null, exempt: true, sum: null };
  }

  const m = /ндс[\s:—-]*(\d{1,2})(?:[.,]\d+)?\s*%/i.exec(t)
    || /(\d{1,2})(?:[.,]\d+)?\s*%\s*ндс/i.exec(t);
  if (!m) return null;

  // Сумма налога, если её тоже написали: «НДС 22% — 1 830,51»
  const after = t.slice(m.index + m[0].length, m.index + m[0].length + 40);
  const ms = /[\s:—-]*([\d][\d\s ]*(?:[.,]\d{1,2})?)/.exec(after);
  const sum = ms ? Number(ms[1].replace(/[\s ]/g, '').replace(',', '.')) : null;

  return { rate: Number(m[1]), exempt: false, sum: Number.isFinite(sum) ? round2(sum) : null };
}

/**
 * Что не так между текстом и документом. Пусто — значит всё сходится.
 *
 * @param {string} text назначение платежа или текст письма
 * @param {{rate:number|null, vat:number|null}} doc что посчитано в документе
 * @returns {string} человеческое описание расхождения или ''
 */
function vatMismatch(text, doc) {
  const said = vatInText(text);
  if (!said) return '';                       // про налог не написано — не наше дело
  const rate = doc && doc.rate == null ? null : Number((doc || {}).rate);

  if (said.exempt && rate != null) {
    return `в назначении написано «без НДС», а документ со ставкой ${rate}%`;
  }
  if (!said.exempt && rate == null) {
    return `в назначении указан НДС ${said.rate}%, а документ без НДС`;
  }
  if (!said.exempt && rate != null && said.rate !== rate) {
    return `в назначении указан НДС ${said.rate}%, а в документе ${rate}%`;
  }

  /*
   * Сумма расходится сильнее, чем на копейку округления.
   *
   * Копейку прощаем намеренно: человек мог посчитать на калькуляторе с другим
   * порядком округления, и придираться к ней значит приучить не читать
   * предупреждения вовсе. А вот разница в рубль — это уже другая ставка или
   * другая база, и её стоит увидеть.
   */
  const vat = doc && doc.vat != null ? round2(doc.vat) : null;
  if (said.sum != null && vat != null && Math.abs(said.sum - vat) > 0.01) {
    return `в назначении сумма НДС ${said.sum}, а посчитано ${vat}`;
  }
  return '';
}

module.exports = { vatInText, vatMismatch };
