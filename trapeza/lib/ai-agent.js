/** Названный документ: счёт, акт, УПД, накладная, платёжка. */
const DOC_NAMED = /(?:счёт|счет|акт|упд|накладн|платёжк|платежк)/i;
/** Предмет, который к выписке документов отношения не имеет вовсе. */
const TAX_ONLY = /(?:усн|псн|ндфл|взнос|кудир|отчётност|отчетност|деклараци|зарплат|кадр|касс[аоу]|патент)/i;
/** Вопросительный оборот: «сколько», «когда», «как платить» — это спрашивают, а не поручают. */
const TAX_QUESTION = /(?:когда|сколько|как\s|надо\s+ли|нужно\s+ли|что\s+такое|почему|обязан)/i;

/**
 * Похоже ли на просьбу выписать документ, а не на вопрос про налоги.
 *
 * Нужно ровно там, где фраза задела налоговые слова, но говорили всё же о
 * документе. Условия нарочно узкие: НДС — единственный налог, который у нас
 * ещё и своя настройка, всё остальное («взносы», «КУДиР», «НДФЛ») — чужая
 * область даже рядом со словом «счёт».
 */
function looksLikeDocRequest(text) {
  const t = String(text || '');
  if (!DOC_NAMED.test(t)) return false;      // документа не называли
  if (TAX_ONLY.test(t)) return false;        // назвали настоящий налоговый предмет
  if (TAX_QUESTION.test(t)) return false;    // это вопрос, а не поручение
  return /ндс/i.test(t);
}

/** К периоду и дате, найденным во фразе, — в ответ (если есть). */
function withWhen(intent, ctx, asPeriod = false) {
  if (!ctx) return intent;
  if (ctx.period) intent.period = ctx.period;
  else if (ctx.date && asPeriod) intent.period = { from: ctx.date, to: ctx.date };
  else if (ctx.date) intent.date = ctx.date;
  return intent;
}

/*
 * Что в боте пока никто не умеет выполнить. Разбор их узнаёт (иначе «повтори
 * вчерашнюю накладную» оставалась бы «повтори» → «регулярные документы», а
 * «напомни Вектору про долг» — «покажи долги»), но отдаёт наружу только когда
 * у бота появится экран: намерение без экрана хуже, чем «не понял» — человек
 * слышит «сейчас сделаю» и не получает ничего. См. тест «у каждого действия
 * разбора есть обработчик в боте»: вписать имя сюда и в bot.js — одна правка.
 */
const NOT_WIRED = new Set(['remind', 'repeat']);

/**
 * Разбор правилами, без модели, со всеми намерениями (в том числе без экрана).
 *
 * @param {string} text
 * @param {{today?:string|Date, clients?:string[]}} [opts] clients — имена клиентов
 *   человека: по ним находятся границы имени и защищаются «Три медведя»
 * @returns {Object|null} null — правила не взялись; weak: true — взялись, но
 *   не уверены (сумма или позиции неоднозначны): модели можно попробовать,
 *   а без неё остаётся вопрос человеку
 */
function parseLocal(text, opts = {}) {
  const raw = String(text || '').trim();
  if (!raw || CANCEL.test(raw)) return null;
  const ctx = prepare(raw, opts);
  const t = ctx.text;
  if (!t) return null;

  const remind = rules.remindFrom(ctx);
  if (remind) return remind;
  const repeat = rules.repeatFrom(ctx);
  if (repeat) return repeat;
  if (rules.RECURRING.test(t) && !rules.AKT.test(t)) {
    const who = rules.recurringWho(ctx);
    return who ? { action: 'recurring', who } : { action: 'recurring' };
  }
  const akt = rules.aktFrom(ctx);
  if (akt) return akt;
  const pay = rules.payFrom(ctx);
  if (pay) return pay;
  const draft = rules.draftFrom(ctx);
  if (draft) return draft;

  for (const q of QUICK) {
    const m = q.re.exec(t);
    // Текст отдаём вторым доводом: правилу нужна вся фраза, а не только то,
    // что попало в скобки шаблона.
    if (m) return q.intent(m, t, ctx);
  }
  return null;
}

/** Для бота: то же, но без намерений, которых он пока не выполняет. */
function quickParse(text, opts = {}) {
  const r = parseLocal(text, opts);
  return r && NOT_WIRED.has(r.action) ? null : r;
}

/**
 * Найти клиента по имени из фразы.
 *
 * Возвращает {cp} только когда уверены. Когда не уверены — {choices}: бот
 * спросит «кого именно вы имели в виду», и это дешевле документа не тому
 * клиенту. Совпадение по корню слова («Заре», «Зарёй», «Зарю» → «Заря») —
 * уверенное; совпадение по началу слова («Север» и «Северный ветер») и по
 * похожести («Зоря», «Вектар» — типичные ошибки распознавания) — только
 * предложение подтвердить.
 */
function matchCp(cps, name) {
  const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е')
    .split(/[^\p{L}\p{N}]+/u).filter((w) => w && !/^(ооо|оао|зао|пао|ип|ао)$/.test(w)).join(' ');
  const want = norm(name);
  if (!want) return {};
  const exact = cps.filter((c) => norm(c.name) === want);
  if (exact.length === 1) return { cp: exact[0] };

  const scored = cps.map((c) => ({ c, s: nameScore(name, c.name) }));
  const hits = scored.filter((x) => x.s.exact > 0);
  if (hits.length) {
    const top = Math.max(...hits.map((x) => x.s.exact));
    const best = hits.filter((x) => x.s.exact === top);
    if (best.length === 1) return { cp: best[0].c };
    return { choices: best.map((x) => x.c).slice(0, 8) };
  }
  const near = scored.filter((x) => x.s.prefix > 0);
  if (near.length) return { choices: near.map((x) => x.c).slice(0, 8) };
  const like = scored.filter((x) => x.s.fuzzy > 0);
  if (like.length) return { choices: like.map((x) => x.c).slice(0, 8) };
  return {};
}

