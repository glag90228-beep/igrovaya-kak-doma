const DOC_TYPES = new Set(['sch', 'schdog', 'usl', 'upd', 'torg12', 'pp', 'dog']);

const SHOW_ACTIONS = ['debts', 'unpaid', 'docs', 'akt', 'cps', 'org', 'vat', 'pay',
  'recurring', 'billing', 'help', 'outofscope', 'kudir'];

const { isoDay } = require('./period');

/** Период из ответа модели: обе даты настоящие и по порядку, иначе его нет. */
function cleanPeriod(p) {
  if (!p || typeof p !== 'object') return null;
  const from = isoDay(p.from);
  const to = isoDay(p.to);
  return from && to && from <= to ? { from, to } : null;
}

function sanitize(raw) {
  if (!raw || typeof raw !== 'object') return { action: 'unknown' };
  const action = String(raw.action || '');
  const who = String(raw.who || '').trim().slice(0, 200);
  if (SHOW_ACTIONS.includes(action)) {
    const out = { action };
    /*
     * Раньше здесь оставалось одно слово action, и «Север оплатил 50 тысяч»,
     * разобранное моделью, теряло и клиента, и сумму: бот спрашивал «по кому
     * вносим» и «сколько» о том, что человек только что сказал.
     */
    if (action === 'pay') {
      out.who = who;
      const amount = Number(raw.amount);
      out.amount = Number.isFinite(amount) && amount > 0 ? Math.min(1e9, Math.round(amount * 100) / 100) : 0;
      out.kind = raw.kind === 'Приход' ? 'Приход' : 'Оплата';
      if (raw.prepay === true) out.prepay = true;
      const d = isoDay(raw.date);
      if (d) out.date = d;
    }
    if (action === 'akt' || action === 'docs') {
      if (who) out.who = who;
      const per = cleanPeriod(raw.period);
      if (per) out.period = per;
    }
    return out;
  }
  if (action !== 'draft') return { action: 'unknown' };
  if (!DOC_TYPES.has(raw.docType)) return { action: 'unknown' };

  const items = (Array.isArray(raw.items) ? raw.items : []).slice(0, 20).map((it) => {
    const row = {
      name: String((it && it.name) || '').trim().slice(0, 200),
      qty: Math.min(100000, Math.max(0, Number((it && it.qty) || 0))) || 1,
      price: Math.min(1e9, Math.max(0, Number((it && it.price) || 0))),
    };
    const unit = String((it && it.unit) || '').trim().slice(0, 20);
    if (unit) row.unit = unit;
    return row;
  }).filter((it) => it.name);

  const res = { action: 'draft', docType: raw.docType, who, items };
  if (raw.vatRate !== undefined) {
    res.vatRate = raw.vatRate == null ? null : Number(raw.vatRate);
    res.priceIncludesVat = Boolean(raw.priceIncludesVat);
  }
  const d = isoDay(raw.date);
  if (d) res.date = d;
  const per = cleanPeriod(raw.period);
  if (per) res.period = per;
  return res;
}

