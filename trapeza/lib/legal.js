/**
 * Оферта и политика обработки персональных данных.
 *
 * Сервис собирает ИНН, ФИО и банковские реквизиты — это персональные данные,
 * значит без политики и согласия работать с публикой нельзя (152-ФЗ).
 * Оферта нужна, чтобы отношения с пользователем были описаны хоть как-то,
 * и чтобы ответственность за содержание документов лежала на том, кто их
 * выпускает, а не на генераторе.
 *
 * Это заготовки. Реквизиты и адреса подставляются из CONFIG, а перед
 * публикацией текст должен посмотреть юрист — генератор не заменяет
 * правовую проверку. Сборка ругается, если что-то не заполнено.
 *
 *   node build-legal.js ../путь/к/сайту
 */

