/** Ответ модели не годится, если она сама сказала «не по теме». */
const OFFTOPIC = 'НЕ_ПО_ТЕМЕ';

/**
 * Как выглядит ответ не из базы.
 *
 * @param {string} text ответ модели
 * @param {string} where чем отвечали: «модель Gemini», имя сайта при поиске
 */
function renderExternal(text, where) {
  const clean = String(text || '').trim();
  if (!clean || clean.includes(OFFTOPIC)) return null;
  return [
    clean,
    '',
    `⚠️ Этого в моей проверенной базе нет. Отвечал: ${where}.`,
    'Мы это не сверяли и за ответ не отвечаем — перед применением проверьте '
    + 'по НК РФ или спросите бухгалтера. Ошибка в налогах стоит штрафа вам, а не нам.',
  ].join('\n');
}

