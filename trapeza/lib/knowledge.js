/** Модель не нашла ответа в отрывках. */
const NOT_FOUND = 'НЕ_НАЙДЕНО';

/**
 * Как выглядит ответ по найденному.
 *
 * Здесь пометка не «отвечала модель», а адрес страницы: владелец просил
 * именно этого — чтобы было видно, с какого сайта взято. Ссылку даём
 * целиком, чтобы её можно было открыть и прочитать самому, а не поверить
 * на слово.
 */
function renderFound(text, results) {
  const body = String(text || '').trim();
  if (!body || body.includes(NOT_FOUND)) return null;
  const links = (results || []).slice(0, 3)
    .map((r) => `• ${r.source}: ${r.url}`);
  return [
    body,
    '',
    'Источник:',
    ...links,
    '',
    'Это пересказ страницы, а не наша проверенная запись: мы её не сверяли '
    + 'и за ответ не отвечаем. Откройте ссылку и прочтите сами — ошибка '
    + 'в налогах стоит штрафа вам, а не нам.',
  ].join('\n');
}

/** Ответ модели не годится, если она сама сказала «не по теме». */
const OFFTOPIC = 'НЕ_ПО_ТЕМЕ';

/**
 * Как выглядит ответ не из базы.
 *
 * @param {string} text ответ модели
 * @param {string} where чем отвечали: «модель Gemini», имя сайта при поиске
 */
function renderExternal(text, where) {
  const clean = String(text || '').trim();
  if (!clean || clean.includes(OFFTOPIC)) return null;
  return [
    clean,
    '',
    `⚠️ Этого в моей проверенной базе нет. Отвечал: ${where}.`,
    'Мы это не сверяли и за ответ не отвечаем — перед применением проверьте '
    + 'по НК РФ или спросите бухгалтера. Ошибка в налогах стоит штрафа вам, а не нам.',
  ].join('\n');
}

