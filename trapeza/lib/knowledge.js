/** Год из вопроса: «в 26 году», «на 2027», «за 2025». */
function yearFrom(text) {
  const t = String(text || '');
  const full = /\b(20\d{2})\b/.exec(t);
  if (full) return Number(full[1]);
  // «в 26 году», «на 27 год» — короткая форма, которой пользуются чаще.
  const short = /\b(\d{2})\s*(?:год|г\b)/i.exec(t);
  if (short) return 2000 + Number(short[1]);
  return null;
}

const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е');

/** Есть ли в тексте хотя бы одно слово из списка. */
const hasAny = (text, words) => words.some((w) => norm(text).includes(norm(w)));

/**
 * Найти ответ.
 *
 * Сначала слова темы (ask), потом уточняющие (need). Разделение нужно, чтобы
 * «патент» и «сколько стоит патент» не слиплись с «когда подавать заявление
 * на патент»: тема одна, ответы разные.
 */
function lookup(question) {
  const t = norm(question);
  if (!t.trim()) return null;
  const year = yearFrom(question);

  const candidates = ENTRIES.filter((e) => hasAny(t, e.ask));
  if (!candidates.length) return null;

  /*
   * Запись с уточняющими словами точнее общей — её и берём. Не нашлось
   * уточнения — отвечаем общей записью темы: «расскажи про патент» это
   * законный вопрос, и молчать на него глупо.
   *
   * А вот подставлять ЛЮБУЮ запись темы нельзя: на «когда платить за патент»
   * ответ про лимиты выручки — это не ответ, а вид ответа. Нет подходящей —
   * пусть решает то, что стоит дальше.
   */
  const exact = candidates.filter((e) => e.need.length && hasAny(t, e.need));
  const best = exact[0] || candidates.find((e) => e.general) || null;
  if (!best) return null;

  const covers = year == null || best.checkedFor.includes(year);
  return { entry: best, year, covers };
}

/**
 * Как ответ выглядит для человека.
 *
 * Норма под ответом обязательна и не сокращается: она и есть разница между
 * «бот сказал» и «так написано в законе». Отдельной строкой — что мы не
 * консультанты: ошибётся здесь бот, а платить будет человек.
 */
function render(found) {
  if (!found) return null;
  const { entry, year, covers } = found;
  const src = `${entry.source.law}, ${entry.source.article}`;
  const lines = [entry.answer, '', `Основание: ${src}.`];

  if (!covers) {
    lines.push('', `⚠️ Про ${year} год не скажу: эти цифры проверяли на `
      + `${entry.checkedFor.join(' и ')} год. Ставки и пороги меняют ежегодно — `
      + 'сверьтесь с действующей редакцией.');
  }
  lines.push('', 'Это справка, а не консультация: учёт я не веду и за решения '
    + 'по ним не отвечаю. Перед применением сверьтесь с нормой или с бухгалтером.');
  return lines.join('\n');
}

/** Сколько записей и на какие годы проверены — для владельца. */
function stats() {
  const years = new Set();
  for (const e of ENTRIES) for (const y of e.checkedFor) years.add(y);
  return { count: ENTRIES.length, years: [...years].sort() };
}

