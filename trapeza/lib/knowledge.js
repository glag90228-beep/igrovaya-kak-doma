/**
 * Своя база ответов по налогам и взносам.
 *
 * Зачем она, если есть модель. Модель отвечает уверенно и на то, чего не
 * знает: называет ставку, которой нет, и срок, который отменили. В налогах
 * это стоит не «неудобно», а штраф — и не нам, а тому, кто спросил.
 *
 * Поэтому здесь не «знания модели», а записи: у каждой есть норма, дата, с
 * которой она действует, и год, на который её проверяли. Ответ без нормы
 * наружу не выходит.
 *
 * ── Чего эта база НЕ делает ──
 *
 * Не заменяет бухгалтера и не ведёт учёт. Она отвечает на частые вопросы
 * «сколько», «когда», «кто вправе» и сразу показывает, откуда это взято,
 * чтобы человек мог проверить сам.
 *
 * ── Про устаревание ──
 *
 * Налоговые числа меняются каждый год. Запись, проверенная на 2026 год,
 * на 2027 может врать — и врать убедительно. Поэтому у каждой есть
 * `checkedFor`, и если спрашивают про год, которого запись не покрывает,
 * ответ не выдаётся как факт: выдаётся то, что знаем, с прямой оговоркой.
 *
 * ВАЖНО ДЛЯ ВЛАДЕЛЬЦА. Записи собраны по нормам НК РФ и федеральных законов,
 * но сверить их с официальными источниками из среды разработки нельзя:
 * nalog.gov.ru, pravo.gov.ru, consultant.ru и garant.ru оттуда недоступны.
 * Сверяйте каждую запись сами — поле `source` указывает, где смотреть.
 *
 * И это не формальная оговорка. При первой же сверке выяснилось, что три
 * записи врали: ФЗ от 28.11.2025 № 425-ФЗ снизил втрое сразу два порога —
 * НДС на УСН и лимит патента, оба с 60 млн до 20 млн с 1 января 2026 года,
 * — а записи уверенно называли 60 и были помечены «проверено на 2026».
 * Сработала ровно та беда, от которой база и строилась: верная ссылка на
 * настоящую статью при неверном числе. Такому верят охотнее всего.
 *
 * Отсюда два правила, и оба проверяются прогоном:
 *   • у каждой записи в checkedFor стоит текущий год — иначе прогон краснеет
 *     и база не переживёт год незаметно;
 *   • рядом с каждой суммой в миллионах назван год, к которому она
 *     относится. «Лимит 20 млн» без года — это будущая ошибка.
 */

