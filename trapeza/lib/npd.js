'use strict';

/**
 * Налог на профессиональный доход: напоминание про чек.
 *
 * Зачем это здесь. Самозанятый и ИП на НПД работают по другому закону, чем
 * все остальные наши пользователи. Счёт и акт им выписывать можно и нужно,
 * но сами по себе они ничего не закрывают: доход считается принятым только
 * когда сформирован чек в «Моём налоге» (ФЗ от 27.11.2018 № 422-ФЗ, ст. 14).
 * Без чека заказчик не может принять расход, а у самого плательщика доход в
 * приложении не появится — и налог не начислится.
 *
 * Забывают об этом постоянно, и именно на безналичной оплате: деньги пришли
 * на счёт молча, документ уже выписан, всё выглядит законченным. Поэтому
 * напоминаем ровно в тот момент, когда человек отмечает оплату.
 *
 * Сроки в законе разные, и это важно:
 *   • наличные и электронные средства платежа — чек в момент расчёта;
 *   • безналичный перевод — не позднее 9-го числа месяца, следующего за
 *     месяцем, в котором пришли деньги (ст. 14 ч. 3).
 * Мы имеем дело со вторым случаем: наши документы оплачивают переводом.
 *
 * Чего мы не делаем. Чек за человека не формируем и формировать не будем:
 * это заявление в налоговую от его имени. Официального программного доступа
 * у нас нет, а подбирать чужие пароли к личному кабинету — не работа
 * бухгалтерской программы. Наше дело — напомнить и открыть приложение.
 */

/**
 * «Мой налог» — личный кабинет плательщика НПД.
 *
 * Адрес один на всё: на телефоне с установленным приложением система
 * открывает его, без приложения — тот же кабинет в браузере. Собственную
 * схему вида moynalog:// не выдумываем: официально она не описана, а
 * несуществующая ссылка молча ничего не открывает, и человек решит, что
 * сломались мы.
 */
const LK_URL = 'https://lknpd.nalog.ru/';

/** Организация на НПД? Признак ставит сам человек — вывести его неоткуда. */
const isNpd = (org) => Boolean(org && Number(org.npd));

/**
 * До какого числа надо выдать чек по деньгам, пришедшим переводом.
 * @param {string} paidISO дата оплаты, YYYY-MM-DD
 * @returns {string} тоже YYYY-MM-DD
 */
function chequeDue(paidISO) {
  const m = /^(\d{4})-(\d{2})-\d{2}$/.exec(String(paidISO || ''));
  if (!m) return '';
  const year = Number(m[1]);
  const month = Number(m[2]);          // 1..12
  const next = month === 12 ? { y: year + 1, m: 1 } : { y: year, m: month + 1 };
  return `${next.y}-${String(next.m).padStart(2, '0')}-09`;
}

/** dd.mm.yyyy — как принято во всех наших текстах. */
const ru = (iso) => {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ''));
  return m ? `${m[3]}.${m[2]}.${m[1]}` : '';
};

/**
 * Текст напоминания после отметки оплаты — или null, если оно ни к чему.
 *
 * @param {object} org организация пользователя
 * @param {{paidAt:string, cpName?:string, total?:number}} what
 */
function chequeReminder(org, what = {}) {
  if (!isNpd(org)) return null;
  const due = chequeDue(what.paidAt);
  return {
    url: LK_URL,
    text: 'Не забудьте выдать чек в «Моём налоге»'
      + (what.cpName ? ` — ${what.cpName}` : '')
      + '.\n\nБез чека доход не попадёт в приложение, налог не начислится, '
      + 'а заказчик не сможет принять расход.'
      + (due ? `\n\nПо переводу на счёт чек можно выдать до ${ru(due)} — `
        + 'это 9-е число следующего месяца (ФЗ № 422-ФЗ, ст. 14).' : ''),
  };
}

module.exports = { LK_URL, isNpd, chequeDue, chequeReminder };
