'use strict';

/**
 * Книга учёта доходов: строки из банковской выписки.
 *
 * Зачем это здесь. Бот до сих пор честно отказывался от КУДиР — «нужен
 * доступ к вашему банку и кассе, а у меня его нет». Доступ появился:
 * выписка разбирается в lib/bank-statement.js и отдаёт поступления с датой,
 * суммой, контрагентом и назначением. Этого хватает, чтобы собрать раздел
 * доходов — но не хватает, чтобы собрать его молча.
 *
 * ГЛАВНОЕ ПРАВИЛО МОДУЛЯ: не угадывать.
 *
 * Приход на счёт — это ещё не доход. Свои же деньги, займ, возврат от
 * поставщика, ошибочный платёж, возврат налога — всё это приходит теми же
 * платёжками и в книгу попадать не должно. Ошибка в любую сторону дорога:
 * лишняя строка — переплата налога, недостающая — занижение базы, а это
 * уже ст. 122 НК и штраф тому, кто книгу подписал.
 *
 * Поэтому у классификации три исхода, а не два: «доход», «не доход» и
 * «не знаю». Третий не прячется и не считается нулём — он возвращается
 * человеку отдельным списком. Книга, в которой десять строк разнесены и
 * одна спрошена, полезна. Книга, в которой одиннадцатая тихо пропала,
 * опаснее, чем её отсутствие.
 *
 * Что модуль умеет и чего не умеет — см. buildIncomeBook ниже.
 */

const { round2 } = require('./money');

/* ------------------------------------------------------------------ *
 * Словари назначений
 *
 * Ищем по назначению платежа, потому что это единственное поле, где банк
 * пишет смысл операции. Формулировки берём в том виде, в каком их пишут
 * банки и бухгалтеры, а не в каком они звучат в НК.
 * ------------------------------------------------------------------ */

/** Не доход: собственные деньги предпринимателя. */
const OWN_FUNDS = [
  'собственные средства', 'собственных средств', 'пополнение счета',
  'пополнение расчетного счета', 'внесение наличных', 'взнос наличными',
  'перевод между своими', 'перевод собственных', 'пополнение счёта',
];

/** Не доход: заёмные деньги. Тело займа доходом не становится. */
const LOANS = [
  'по договору займа', 'предоставление займа', 'возврат займа',
  'погашение займа', 'выдача кредита', 'кредитных средств', 'транш по кредит',
  'основного долга по кредит',
];

/** Не доход: деньги вернулись обратно к нам. */
const RETURNS_TO_US = [
  'возврат излишне', 'возврат переплаты', 'возврат ошибочно',
  'возврат денежных средств по счет', 'возврат аванса поставщик',
  'возврат от поставщик', 'возврат товара поставщик',
];

/** Не доход: бюджет вернул налог. */
const BUDGET = [
  'возврат налога', 'возврат излишне уплаченного налога', 'из бюджета',
  'возмещение ндс', 'единого налогового счета', 'уфк по',
];

/** Доход: обычная выручка. */
const REVENUE = [
  'оплата по счет', 'оплата счет', 'за услуги', 'за товар', 'за работы',
  'по договору', 'предоплата', 'аванс по', 'авансовый платеж',
  'за выполненные работы', 'за оказанные услуги', 'реализаци',
  'оплата по договору', 'частичная оплата',
];

/**
 * Спрашиваем человека: эквайринг.
 *
 * Банк зачисляет выручку за вычетом своей комиссии, а доходом признаётся
 * ПОЛНАЯ сумма, которую заплатил покупатель (комиссия — это расход, а на
 * «доходах» он ещё и не учитывается). Записать в книгу зачисленную сумму
 * значит занизить доход на комиссию. Сколько её удержали, в назначении
 * обычно не пишут, поэтому здесь мы не угадываем никогда.
 */
const ACQUIRING = [
  'эквайринг', 'эквайринга', 'торговая уступка', 'возмещение по операциям с картами',
  'реестр операций', 'интернет-эквайринг',
];

/**
 * Спрашиваем человека: обеспечительный платёж.
 *
 * Задаток и обеспечительный платёж становятся доходом не в день получения,
 * а в день зачёта в счёт оплаты — и день этот из выписки не виден.
 */
const DEPOSIT = [
  'обеспечительный платеж', 'обеспечительного платежа', 'задаток',
  'гарантийный взнос', 'залоговая сумма',
];

/** Расход, уменьшающий доход: вернули деньги покупателю. */
const REFUND_OUT = [
  'возврат покупателю', 'возврат денежных средств покупател',
  'возврат предоплаты покупател', 'возврат оплаты по счет',
  'возврат средств за неоказанн',
];

const norm = (s) => String(s || '').toLowerCase().replace(/ё/g, 'е');

const hasAny = (text, words) => words.some((w) => text.includes(norm(w)));

/**
 * Классификация одной строки выписки.
 *
 * Порядок проверок важен и он не алфавитный. Сначала то, что точно НЕ доход
 * и то, что требует человека, и только потом выручка: «возврат оплаты по
 * счету» содержит «оплата по счет», и если начать с выручки, возврат станет
 * доходом. Частное правило всегда раньше общего.
 *
 * @returns {{kind:'income'|'not_income'|'refund'|'ask', reason:string}}
 */
function classify(row) {
  const p = norm(row && row.purpose);
  const incoming = !!(row && row.incoming);

  if (!p.trim()) {
    return { kind: 'ask', reason: 'назначение платежа пустое' };
  }

  if (!incoming) {
    // Расход интересует нас только в одном случае: мы вернули деньги
    // покупателю. Такой возврат уменьшает доход того периода, в котором
    // он сделан. Всё остальное к книге доходов отношения не имеет.
    if (hasAny(p, REFUND_OUT)) {
      return { kind: 'refund', reason: 'возврат покупателю уменьшает доход' };
    }
    return { kind: 'not_income', reason: 'расход, в книгу доходов не идёт' };
  }

  if (hasAny(p, ACQUIRING)) {
    return { kind: 'ask', reason: 'эквайринг: зачислено за вычетом комиссии, а доход — полная сумма' };
  }
  if (hasAny(p, DEPOSIT)) {
    return { kind: 'ask', reason: 'обеспечительный платёж: доход возникает в день зачёта, не получения' };
  }
  if (hasAny(p, OWN_FUNDS)) {
    return { kind: 'not_income', reason: 'собственные средства' };
  }
  if (hasAny(p, LOANS)) {
    return { kind: 'not_income', reason: 'заёмные средства' };
  }
  if (hasAny(p, RETURNS_TO_US)) {
    return { kind: 'not_income', reason: 'возврат нам, не выручка' };
  }
  if (hasAny(p, BUDGET)) {
    return { kind: 'not_income', reason: 'возврат из бюджета' };
  }
  if (hasAny(p, REVENUE)) {
    return { kind: 'income', reason: 'выручка' };
  }

  return { kind: 'ask', reason: 'по назначению не разобрать' };
}

/**
 * Основание записи — графа 2 книги.
 *
 * В книге это «дата и номер первичного документа». Для поступления на счёт
 * первичный документ — платёжное поручение: его номер есть в выписке.
 */
function basisOf(row) {
  const num = String((row && row.doc) || '').trim();
  const date = ruDate(row && row.date);
  if (num && date) return `п/п № ${num} от ${date}`;
  if (date) return `выписка банка от ${date}`;
  return 'выписка банка';
}

/** ISO → дд.мм.гггг. В книгу даты печатаются по-русски. */
function ruDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso || ''));
  return m ? `${m[3]}.${m[2]}.${m[1]}` : '';
}

/** Попадает ли дата в период. Обе границы включительно. */
function inPeriod(iso, from, to) {
  const d = String(iso || '');
  if (!d) return false;
  if (from && d < from) return false;
  if (to && d > to) return false;
  return true;
}

/* ------------------------------------------------------------------ *
 * Какую книгу вести этой организации
 * ------------------------------------------------------------------ */

const TAX_MODES = {
  usn_income: 'УСН «доходы»',
  usn_minus: 'УСН «доходы минус расходы»',
  psn: 'Патент',
};

/**
 * Единственная формулировка отказа из-за НДС.
 *
 * Держим её константой, а не двумя одинаковыми строками: решатель и сборщик
 * отказывают по одной причине, и разъехавшиеся тексты означали бы, что
 * человек получает разные объяснения в зависимости от того, каким путём
 * дошёл до отказа.
 */
const VAT_BLOCK = 'Вы платите НДС на УСН. В доходы налог, предъявленный покупателю, '
  + 'не входит (ст. 248 НК), а вычесть его из выписки не из чего: ставку '
  + 'в назначении платежа пишут не всегда. Такую книгу собирайте с бухгалтером.';

/**
 * Решение по карточке организации: что за книга и можно ли её собрать.
 *
 * Отдать не ту форму хуже, чем не отдать никакой: книга — налоговый
 * регистр, и патентная книга вместо упрощенческой это не «похожий файл», а
 * неверный документ на проверке. Поэтому во всех сомнительных случаях
 * отказываем и объясняем, а не выбираем вероятное.
 *
 * @returns {{mode:string, vatPayer:boolean, blocked:string, needs:string}}
 */
function bookFor(org) {
  const o = org || {};
  const mode = String(o.tax_mode || '');
  const raw = o.vat_rate;
  const rate = raw === '' || raw == null ? null : Number(raw);
  const vatPayer = Number.isFinite(rate);
  const no = (blocked, needs = '') => ({ mode: '', vatPayer, blocked, needs });

  if (Number(o.npd)) {
    return no('Вы на налоге на профессиональный доход. КУДиР самозанятые не ведут — '
      + 'учёт ведётся в приложении «Мой налог», и книга там не требуется.');
  }
  if (!mode) {
    return no('Не знаю ваш режим налогообложения, а от него зависит форма книги: '
      + 'у УСН и у патента они разные. Укажите режим в карточке организации.', 'tax_mode');
  }
  if (mode === 'usn_minus') {
    return no('На «доходах минус расходах» книгу собрать не возьмусь. Расходы там — '
      + 'закрытый перечень статьи 346.16 НК, и почти у каждого пункта своё условие: '
      + 'товары для перепродажи списываются только после продажи и оплаты, основные '
      + 'средства — долями по кварталам. Из назначения платежа это не выводится.');
  }
  if (mode === 'psn') {
    /*
     * Ставка НДС в карточке при патенте означает совмещение режимов: учёт
     * тогда ведётся раздельно и книг получается две, каждая по своим
     * доходам. Развести их по одной выписке нельзя — в платёжке не
     * написано, к какому режиму относится поступление.
     */
    if (vatPayer) {
      return no('В карточке стоит ставка НДС, а режим — патент. Похоже на совмещение '
        + 'с УСН: тогда книги две и доходы в них разделяются по видам деятельности, '
        + 'а из выписки этого не видно. Такую книгу собирайте с бухгалтером.');
    }
    return { mode: 'psn', vatPayer: false, blocked: '', needs: '' };
  }
  if (mode === 'usn_income') {
    if (vatPayer) return no(VAT_BLOCK);
    return { mode: 'usn', vatPayer: false, blocked: '', needs: '' };
  }
  return no(`Режим «${mode}» я не знаю. Укажите его заново в карточке организации.`, 'tax_mode');
}

/**
 * Собрать раздел доходов за период.
 *
 * Чего модуль НЕ делает, и это осознанно:
 *
 *   • не ведёт «доходы минус расходы». Расходы там — закрытый перечень
 *     ст. 346.16 с отдельными условиями почти у каждого пункта (товары для
 *     перепродажи — только после продажи И оплаты, основные средства —
 *     долями по кварталам). Это учёт, а не разбор назначения платежа;
 *   • не считает доход плательщика НДС. С 2025 года НДС на УСН есть, а в
 *     доходы по ст. 248 НК предъявленный покупателю налог не входит —
 *     значит из каждой строки его надо вычесть. Пока вычитать неоткуда:
 *     ставка в назначении пишется не всегда и не всеми. Поэтому для
 *     плательщика НДС книга не собирается вовсе;
 *   • не заполняет разделы про взносы, убытки и основные средства;
 *   • не считает наличную выручку — в выписке её нет.
 *
 * @param {Array} rows   строки из parseStatement
 * @param {Object} opts  {from, to, vatPayer}
 */
function buildIncomeBook(rows, opts = {}) {
  const { from = '', to = '', vatPayer = false } = opts;

  // Страховка на случай, если наверху решатель обошли: книга плательщика
  // НДС не должна собраться ни одним путём.
  if (vatPayer) {
    return { blocked: VAT_BLOCK, rows: [], ask: [], total: 0, refunds: 0 };
  }

  /*
   * Сортировка по дате — не косметика. Книга ведётся в хронологическом
   * порядке, и номер строки в ней ссылается на место в этом порядке.
   * Выписки же приходят как угодно: банки выгружают по счетам, человек
   * грузит два файла за разные месяцы подряд. Пронумеруй как пришло — и
   * книга получится с датами вразнобой, то есть непригодной.
   *
   * Сортировка устойчивая: при равной дате порядок внутри дня остаётся
   * таким, каким его дал банк, — это и есть порядок проводок за день.
   */
  const list = (Array.isArray(rows) ? rows.slice() : [])
    .map((r, i) => ({ r, i }))
    .sort((a, b) => String(a.r && a.r.date).localeCompare(String(b.r && b.r.date)) || a.i - b.i)
    .map((x) => x.r);
  const book = [];
  const ask = [];
  let n = 0;
  let income = 0;
  let refunds = 0;

  for (const row of list) {
    if (!inPeriod(row && row.date, from, to)) continue;

    const amount = round2(Number((row && row.amount) || 0));
    if (!(amount > 0)) continue;

    const { kind, reason } = classify(row);

    if (kind === 'ask') {
      ask.push({
        date: row.date, amount, name: row.name || '', purpose: row.purpose || '', reason,
      });
      continue;
    }
    if (kind === 'not_income') continue;

    // Возврат покупателю уменьшает доход — в книге он отрицательной суммой
    // в той же графе, а не отдельным разделом.
    const signed = kind === 'refund' ? round2(-amount) : amount;
    n += 1;
    book.push({
      n,
      date: row.date,
      dateRu: ruDate(row.date),
      basis: basisOf(row),
      what: kind === 'refund'
        ? `Возврат покупателю${row.name ? ` — ${row.name}` : ''}`
        : `Оплата от ${row.name || 'покупателя'}`,
      amount: signed,
    });
    if (signed < 0) refunds = round2(refunds + amount);
    else income = round2(income + amount);
  }

  return {
    blocked: '',
    rows: book,
    ask,
    total: round2(income - refunds),
    income,
    refunds,
  };
}

module.exports = {
  classify, buildIncomeBook, bookFor, basisOf, ruDate, inPeriod, TAX_MODES, VAT_BLOCK,
};
