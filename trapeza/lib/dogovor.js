'use strict';

/**
 * Договор возмездного оказания услуг — заполняется реквизитами, которые
 * пользователь уже ввёл, так что от него нужны только предмет, цена и срок.
 *
 * Это рабочая заготовка, а не индивидуальный договор под конкретную сделку:
 * так и написано в самом документе. Формулировки взяты общие, по главе 39
 * ГК РФ; всё, что специфично (штрафы, эксклюзив, интеллектуальная
 * собственность), в шаблон не тащим — там нужен юрист, а не генератор.
 */

const { esc, ru, page, formatMoney, amountInWords } = require('./doc-html');

const CSS = `
  .dg h2 { font-size: 13px; color: #1f2760; margin: 14px 0 5px; }
  .dg p { margin: 5px 0; text-align: justify; }
  .dg ol { margin: 4px 0 4px 18px; padding: 0; }
  .dg li { margin: 3px 0; text-align: justify; }
  .dg .parties { display: flex; gap: 28px; margin-top: 26px; }
  .dg .parties > div { flex: 1; }
  .dg .parties .line { border-top: 1px solid #333; margin-top: 30px; padding-top: 3px; font-size: 10px; }
  .dg .req { font-size: 10.5px; line-height: 1.45; }
`;

const nameOf = (p) => esc(p.full_name || p.name || '');

function requisites(p) {
  const rows = [
    p.inn ? `ИНН ${esc(p.inn)}` : '',
    p.kpp ? `КПП ${esc(p.kpp)}` : '',
    p.address ? `Адрес: ${esc(p.address)}` : '',
    p.bank_name ? `Банк: ${esc(p.bank_name)}` : '',
    p.bik ? `БИК ${esc(p.bik)}` : '',
    p.acc ? `Р/с ${esc(p.acc)}` : '',
    p.corr_acc ? `К/с ${esc(p.corr_acc)}` : '',
  ].filter(Boolean);
  return rows.join('<br>');
}

/**
 * @param doc { number, date, subject, price?, priceText?, term?, city?, prepay? }
 *   price — фиксированная сумма; если её нет, платим по счетам (priceText).
 */
function buildDogovorHtml({ org, cp, doc }) {
  const city = doc.city || org.city || 'Ижевск';
  /*
   * Оговорка про упрощёнку — только тому, кто на упрощёнке.
   *
   * Раньше она печаталась всегда, и плательщик НДС получал договор,
   * заявляющий его же контрагенту, что налога нет. Это не описка в бланке,
   * а ложное условие в подписанном документе: контрагент вправе на него
   * сослаться, а вычет по такому договору не получит. В соседних бланках
   * ровно для этого заведена usnNote — накладная и УПД ею пользуются,
   * договор был единственным, кто решал за всех.
   */
  const vatPayer = org && org.vat_rate != null && org.vat_rate !== ''
    && Number.isFinite(Number(org.vat_rate));
  const priceClause = Number(doc.price) > 0
    ? `Стоимость услуг по настоящему Договору составляет <b>${formatMoney(doc.price)} руб.</b>
       (${amountInWords(doc.price)})${vatPayer ? ''
    : ', НДС не облагается в связи с применением Исполнителем упрощённой системы налогообложения'}.`
    : `Стоимость услуг определяется в счетах Исполнителя на каждую партию услуг
       и считается согласованной с момента оплаты счёта Заказчиком.
       ${doc.priceText ? esc(doc.priceText) : ''}`;

  const prepay = Number(doc.prepay) > 0
    ? `Заказчик вносит предоплату в размере ${esc(String(doc.prepay))}% стоимости услуг
       в течение 3 (трёх) рабочих дней с даты выставления счёта.`
    : 'Оплата производится в течение 5 (пяти) рабочих дней с даты выставления счёта, '
      + 'если стороны письменно не согласовали иной срок.';

  const body = `
    <div class="dg">
      <h1 class="center">ДОГОВОР № ${esc(doc.number || '1')}</h1>
      <p class="center">возмездного оказания услуг</p>
      <p class="center muted small">г. ${esc(city)} · ${ru(doc.date)}</p>
      <hr class="rule">

      <p>${nameOf(org)}, именуемое в дальнейшем «Исполнитель», с одной стороны,
         и ${nameOf(cp)}, именуемое в дальнейшем «Заказчик», с другой стороны,
         вместе именуемые «Стороны», заключили настоящий Договор о нижеследующем.</p>

      <h2>1. Предмет договора</h2>
      <p>1.1. Исполнитель обязуется по заданию Заказчика оказать услуги:
         <b>${esc(doc.subject || 'услуги по согласованию сторон')}</b>,
         а Заказчик обязуется принять и оплатить их.</p>
      <p>1.2. Объём, сроки и состав каждой партии услуг согласуются Сторонами
         в заявке Заказчика и подтверждаются счётом Исполнителя.</p>

      <h2>2. Цена и порядок расчётов</h2>
      <p>2.1. ${priceClause}</p>
      <p>2.2. ${prepay}</p>
      <p>2.3. Обязательство Заказчика по оплате считается исполненным с момента
         зачисления денежных средств на расчётный счёт Исполнителя.</p>

      <h2>3. Порядок сдачи и приёмки</h2>
      <p>3.1. По факту оказания услуг Исполнитель передаёт Заказчику акт об оказании услуг.</p>
      <p>3.2. Заказчик подписывает акт либо направляет мотивированный отказ в течение
         3 (трёх) рабочих дней. Если в этот срок отказ не поступил, услуги считаются
         принятыми без замечаний.</p>

      <h2>4. Ответственность сторон</h2>
      <p>4.1. За нарушение сроков оплаты Заказчик уплачивает пеню 0,1% от просроченной
         суммы за каждый день просрочки, но не более 10% от суммы задолженности.</p>
      <p>4.2. Стороны освобождаются от ответственности при обстоятельствах непреодолимой силы.</p>

      <h2>5. Срок действия</h2>
      <p>5.1. Договор вступает в силу с даты подписания и действует
         ${doc.term ? `до ${esc(doc.term)}` : 'до 31 декабря текущего года'},
         а в части расчётов — до полного исполнения обязательств.</p>
      <p>5.2. Если за 30 дней до окончания срока ни одна из Сторон не заявила о прекращении,
         Договор считается продлённым на тот же срок.</p>

      <h2>6. Прочие условия</h2>
      <p>6.1. Все изменения оформляются письменно и подписываются обеими Сторонами.</p>
      <p>6.2. Документы, переданные по электронной почте или в мессенджерах с адресов
         и номеров, указанных в реквизитах, признаются имеющими силу до обмена оригиналами.</p>
      <p>6.3. Споры разрешаются путём переговоров, при недостижении согласия —
         в арбитражном суде по месту нахождения ответчика.</p>
      <p>6.4. Договор составлен в двух экземплярах, по одному для каждой Стороны.</p>

      <h2>7. Реквизиты и подписи сторон</h2>
      <div class="parties">
        <div>
          <div class="b">Исполнитель</div>
          <div class="req">${nameOf(org)}<br>${requisites(org)}</div>
          <div class="line">${esc(org.signer || '')}</div>
        </div>
        <div>
          <div class="b">Заказчик</div>
          <div class="req">${nameOf(cp)}<br>${requisites(cp)}</div>
          <div class="line">подпись / расшифровка</div>
        </div>
      </div>

      <p class="note">Шаблон общего назначения. Под конкретную сделку условия
         стоит показать юристу — генератор не заменяет правовую проверку.</p>
    </div>`;

  return page(`Договор № ${doc.number || '1'}`, body).replace('</style>', `${CSS}</style>`);
}

module.exports = { buildDogovorHtml };
